import { placementMatrix } from '../core/geometry.js';
import { getMaster, placedInstances } from '../core/document.js';
import { toCurveData, toPathData } from '../core/contour/svg.js';
import { transformPaths } from '../core/shape.js';
import { markMatrix, markPaint, markPathData } from '../core/marks.js';

/**
 * SVG ทั้งหน้า (FR-07.3, FR-07.4, FR-07.9)
 * width/height เป็น มม. และ viewBox 0 0 W H จึง 1 หน่วย = 1 มม. ตรงกับพิกัดเอกสาร
 * เส้นตัดถูกแปลงพิกัดด้วย placementMatrix ชุดเดียวกับภาพแล้วเขียนลงพิกัดตรง ๆ (ไม่ใช้ transform)
 * เพราะซอฟต์แวร์เครื่องตัดบางตัวอ่าน transform ไม่ครบ Bezier ผ่าน affine ได้ตรงโดยไม่คลาดเคลื่อน
 */
export const CUT_COLOR = '#ff00ff';
export const CUT_STROKE_MM = 0.1;

const num = (v) => String(Math.round(v * 1000) / 1000);
const esc = (s) => String(s).replace(/[<>&"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' }[c]));

/** Path data ของเส้นตัดทุกชิ้นในหน้า ในพิกัดกระดาษ (มม.) */
export function pageCutPaths(doc, pageId) {
  const out = [];
  for (const instance of placedInstances(doc, pageId)) {
    const master = getMaster(doc, instance.masterId);
    const { cutline } = master;
    if (!cutline || cutline.stale || !cutline.closedPaths?.length) continue;
    const m = placementMatrix(instance.transform, master.desiredSizeMm);
    const d = cutline.curves ? toCurveData(transformPaths(cutline.curves, m)) : toPathData(transformPaths(cutline.closedPaths, m));
    out.push({ id: instance.id, name: master.name, d });
  }
  return out;
}

function header(doc, title) {
  const { widthMm: W, heightMm: H } = doc.paper;
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${num(W)}mm" height="${num(H)}mm" viewBox="0 0 ${num(W)} ${num(H)}">
<title>${esc(title)}</title>
<desc>units: 1 user unit = 1 mm; origin: top-left of paper; generated by Sticker Layout &amp; Cutline Studio</desc>
`;
}

function cutGroup(doc, pageId) {
  const paths = pageCutPaths(doc, pageId).map((p) => `<path id="cut-${esc(p.id)}" d="${p.d}"/>`);
  return `<g id="CUT_LINES" fill="none" stroke="${CUT_COLOR}" stroke-width="${CUT_STROKE_MM}" stroke-linejoin="round">
${paths.join('\n')}
</g>
`;
}

function markElements(marks) {
  return marks.map((mark) => {
    const p = markPaint(mark);
    const m = markMatrix(mark).map(num).join(' ');
    const stroke = p.stroke !== 'none' && p.lineMm > 0 ? ` stroke="${p.stroke}" stroke-width="${num(p.lineMm)}"` : ' stroke="none"';
    return `<path id="mark-${esc(mark.id)}" transform="matrix(${m})" d="${markPathData(mark)}" fill="${p.fill}"${stroke}/>`;
  }).join('\n');
}

/** กลุ่มมาร์คอ้างอิงในไฟล์ตัด ระบุชัดว่าไม่ใช่เส้นตัด ไม่มี stroke เพื่อไม่ให้ถูกสั่งตัด (FR-07.9) */
function marksReference(marks) {
  const items = marks.map((mark) => ({ ...mark, stroke: 'none', fill: mark.fill !== 'none' ? mark.fill : '#000000' }));
  return `<g id="REG_MARKS_REFERENCE_NOT_CUT" data-cut="false" fill="#000000" stroke="none">
<desc>Registration marks for reference only. NOT A CUT LINE. มาร์คอ้างอิงเท่านั้น ไม่ใช่เส้นตัด</desc>
${markElements(items)}
</g>
`;
}

/** Cutline Only SVG: เฉพาะกลุ่ม CUT_LINES และเลือกใส่มาร์คอ้างอิงได้ */
export function cutSvg(doc, pageId, { marks = 'none', title } = {}) {
  const ref = marks === 'reference' && doc.marks?.length ? marksReference(doc.marks) : '';
  return `${header(doc, title ?? `${doc.name} cut`)}${cutGroup(doc, pageId)}${ref}</svg>
`;
}

/**
 * Combined SVG: ARTWORK / CUT_LINES / REG_MARKS แยกกลุ่ม (FR-07.4)
 * ARTWORK เป็นภาพทั้งหน้าที่วาดด้วยตัววาดเดียวกับไฟล์พิมพ์ จึงรวม Bleed และการตัดภาพพื้นทึบเหมือนกัน
 */
export function combinedSvg(doc, pageId, { artworkHref, includeMarks = true, title } = {}) {
  const { widthMm: W, heightMm: H } = doc.paper;
  const art = artworkHref
    ? `<g id="ARTWORK"><image x="0" y="0" width="${num(W)}" height="${num(H)}" preserveAspectRatio="none" xlink:href="${artworkHref}" href="${artworkHref}"/></g>\n`
    : '<g id="ARTWORK"/>\n';
  const marks = includeMarks && doc.marks?.length
    ? `<g id="REG_MARKS" data-cut="false">\n${markElements(doc.marks)}\n</g>\n`
    : '';
  return `${header(doc, title ?? `${doc.name} combined`)}${art}${cutGroup(doc, pageId)}${marks}</svg>
`;
}
